/// Julia Base's natural logarithm for a nonnegative Float64.
pub fn log(mut x: f64) -> f64 {
    if x > 0.0 {
        if x == f64::INFINITY {
            return x;
        }
        if 0.9394130628134757 < x && x < 1.0644944589178595 {
            return procedure2(x - 1.0);
        }
        let mut word = x.to_bits();
        let mut exponent = ((word >> 52) & 0x7ff) as i32;
        if exponent == 0 {
            x *= 1.8014398509481984e16;
            word = x.to_bits();
            exponent = ((word >> 52) & 0x7ff) as i32 - 54;
        }
        exponent -= 1023;
        let y = f64::from_bits((word & 0x000f_ffff_ffff_ffff) | 0x3ff0_0000_0000_0000);
        let rounded = (y + 3.5184372088832e13) - 3.5184372088832e13;
        procedure1(y, exponent as f64, rounded, y - rounded)
    } else if x == 0.0 {
        f64::NEG_INFINITY
    } else if x.is_nan() {
        f64::NAN
    } else {
        panic!("log domain: {x}")
    }
}
/// Julia Base's natural logarithm of one plus a Float64 greater than or equal to -1.
pub fn log1p(x: f64) -> f64 {
    if x > -1.0 {
        if x == f64::INFINITY {
            return x;
        }
        if -1.1102230246251565e-16 < x && x < 1.1102230246251565e-16 {
            return x;
        }
        if -0.06058693718652422 < x && x < 0.06449445891785943 {
            return procedure2(x);
        }
        let z = 1.0 + x;
        let word = z.to_bits();
        let scale = f64::from_bits(0x7fe0_0000_0000_0000 - (word & 0xfff0_0000_0000_0000));
        let exponent = ((word >> 52) & 0x7ff) as i32 - 1023;
        let correction = if exponent > 0 {
            1.0 - (z - x)
        } else {
            x - (z - 1.0)
        };
        let y = f64::from_bits((word & 0x000f_ffff_ffff_ffff) | 0x3ff0_0000_0000_0000);
        let rounded = (y + 3.5184372088832e13) - 3.5184372088832e13;
        procedure1(
            y,
            exponent as f64,
            rounded,
            (y - rounded) + correction * scale,
        )
    } else if x == -1.0 {
        f64::NEG_INFINITY
    } else if x.is_nan() {
        f64::NAN
    } else {
        panic!("log1p domain: {x}")
    }
}
