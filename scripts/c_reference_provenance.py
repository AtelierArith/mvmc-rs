#!/usr/bin/env python3
"""Classify C-source provenance records after the mVMC 1.3.0 -> 1.4.0 move (#682).

Every tracked file outside `extern/` that records the SHA-256 of a C reference
source file is classified by the sources it cites:

* `1.4.0`: every cited C source hash is a 1.4.0 hash (regenerated or re-hashed
  in #682, or the source is byte-identical in both releases);
* `historical 1.3.0`: at least one cited source is a 1.3.0 hash of a file that
  changed in 1.4.0. These fixtures and records were generated from the
  1.3.0 reference (`d73d06bd`) and are kept unchanged as historical evidence.

Only hashes of C sources under `src/` count (`.c`, `.h`, `.cc`, `.tcc`, `.f`,
`.f90`, `.F90`); hashes of copied input files (for example StdFace `ref/*.def`
inputs) are ignored. The release hashes are read from the submodule's git
objects, so this needs `extern/mVMC-1.4.0` with its history (`d73d06bd` must
be reachable). The default mode verifies `tests/fixtures/C_REFERENCE_PROVENANCE.md`;
`--write` regenerates it. This is an optional developer tool; Cargo builds and
Rust tests never run it.

    uv run --no-project python scripts/c_reference_provenance.py [--write]
"""
from __future__ import annotations

import argparse
import hashlib
import re
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SUBMODULE = ROOT / "extern/mVMC-1.4.0"
OLD, NEW = "d73d06bd529d3b2573f38eb5817c4a5f52971006", "e83aa6cb1e37bfc4876848787ed2f61721a7e972"
REGISTRY = ROOT / "tests/fixtures/C_REFERENCE_PROVENANCE.md"
SOURCE = re.compile(r"^src/.*\.(c|h|cc|tcc|f|f90|F90)$")
HEX = re.compile(r"\b[0-9a-f]{64}\b")


def release_hashes(rev: str) -> dict[str, str]:
    """SHA-256 of every C source blob under src/ at `rev`, keyed by path."""
    listing = subprocess.run(["git", "-C", str(SUBMODULE), "ls-tree", "-r", rev, "--", "src"],
                             check=True, capture_output=True, text=True).stdout
    blobs = {}
    for line in listing.splitlines():
        meta, path = line.split("\t", 1)
        kind, obj = meta.split()[1:3]
        if kind == "blob" and SOURCE.match(path):
            blobs[path] = obj
    batch = subprocess.run(["git", "-C", str(SUBMODULE), "cat-file", "--batch"], check=True,
                           input="\n".join(blobs.values()).encode() + b"\n",
                           capture_output=True).stdout
    out, pos = {}, 0
    for path, obj in blobs.items():
        header_end = batch.index(b"\n", pos)
        size = int(batch[pos:header_end].split()[2])
        data = batch[header_end + 1:header_end + 1 + size]
        pos = header_end + 1 + size + 1
        out[path] = hashlib.sha256(data).hexdigest()
    return out


def tracked_files() -> list[str]:
    listing = subprocess.run(["git", "-C", str(ROOT), "ls-files"], check=True,
                             capture_output=True, text=True).stdout.split("\n")
    return [f for f in listing if f and not f.startswith("extern/") and f != REGISTRY.relative_to(ROOT).as_posix()]


def classify():
    old, new = release_hashes(OLD), release_hashes(NEW)
    changed = {p for p in old if new.get(p) != old[p]}
    by_hash: dict[str, set[tuple[str, str]]] = defaultdict(set)
    for path, digest in old.items():
        by_hash[digest].add((path, "1.3.0" if path in changed else "both"))
    for path, digest in new.items():
        if path in changed or path not in old:
            by_hash[digest].add((path, "1.4.0"))
    rows = []
    for rel in tracked_files():
        try:
            text = (ROOT / rel).read_text()
        except (UnicodeDecodeError, IsADirectoryError, FileNotFoundError):
            continue
        cited = set()
        for digest in set(HEX.findall(text)):
            cited |= by_hash.get(digest, set())
        if not cited:
            continue
        historical = sorted(p for p, tag in cited if tag == "1.3.0")
        status = "historical 1.3.0" if historical else "1.4.0"
        rows.append((rel, status, historical, sorted(p for p, tag in cited if tag != "1.3.0")))
    return changed, rows


def render(changed, rows) -> str:
    hist = [r for r in rows if r[1] == "historical 1.3.0"]
    cur = [r for r in rows if r[1] == "1.4.0"]
    lines = [
        "# C reference provenance after the move to mVMC 1.4.0 (#682)",
        "",
        "Generated by `scripts/c_reference_provenance.py --write`; do not edit by hand.",
        "",
        "The C authority is `extern/mVMC-1.4.0` (`v1.4.0`, `" + NEW[:8] + "`). Files below record",
        "SHA-256 hashes of C reference sources. A file is **historical 1.3.0** when it",
        "cites the 1.3.0 hash (`" + OLD[:8] + "`) of a source that changed in 1.4.0: it was",
        "generated from the 1.3.0 reference, is kept unchanged as evidence and is not",
        "a claim about 1.4.0. A file is **1.4.0** when every cited source hash belongs",
        "to 1.4.0, either because the source is byte-identical in both releases or",
        "because the record was re-hashed or regenerated against 1.4.0 in #682.",
        "Fixture files are not hand-edited, so this registry is the label.",
        "",
        "The nested submodules (StdFace `6fa4ef1f`, blis `a32257ee`, pfapack `ebaa11b7`) are",
        "pinned identically by both releases, so records of their files are unaffected",
        "and are not listed. Benchmark results under `benchmark/**/results/` and other",
        "dated evidence that name `d73d06bd` or `mVMC 1.3.0` without hashes are historical",
        "1.3.0 records as well.",
        "",
        f"{len(changed)} C sources under `src/` changed between the releases. "
        f"{len(hist)} files are historical 1.3.0 and {len(cur)} files cite only 1.4.0 hashes.",
        "",
        "## Historical 1.3.0",
        "",
        "| File | Changed 1.3.0 sources cited |",
        "| --- | --- |",
    ]
    for rel, _, historical, _ in hist:
        lines.append(f"| `{rel}` | " + ", ".join(f"`{Path(p).name}`" for p in historical) + " |")
    lines += ["", "## 1.4.0", "", "| File | Sources cited |", "| --- | --- |"]
    for rel, _, _, current in cur:
        names = sorted({Path(p).name for p in current})
        shown = ", ".join(f"`{n}`" for n in names[:8]) + (f", +{len(names) - 8}" if len(names) > 8 else "")
        lines.append(f"| `{rel}` | {shown} |")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    changed, rows = classify()
    text = render(changed, rows)
    if args.write:
        REGISTRY.write_text(text)
        print(f"wrote {REGISTRY.relative_to(ROOT)}")
        return 0
    if not REGISTRY.exists() or REGISTRY.read_text() != text:
        print(f"{REGISTRY.relative_to(ROOT)} is stale; rerun with --write", file=sys.stderr)
        return 1
    print(f"{REGISTRY.relative_to(ROOT)} is current")
    return 0


if __name__ == "__main__":
    sys.exit(main())
